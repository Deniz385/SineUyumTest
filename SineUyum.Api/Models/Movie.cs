using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace SineUyum.Api.Models
{
    public class Movie
    {
        [Key]
        [DatabaseGenerated(DatabaseGeneratedOption.None)] // The id is not generated by the database
        public int Id { get; set; } // Same as the movie's id on TMDb

        public string Title { get; set; } = string.Empty;

        public string? PosterPath { get; set; }

        // When the genres were last processed from TMDb (null: never). Genres were
        // never written before; older movies are filled in in the background.
        public DateTime? GenresSyncedAt { get; set; }

        // TMDb overall average (0-10); used to find the "most contrarian rating".
        public double? TmdbVoteAverage { get; set; }

        public ICollection<MovieGenre> MovieGenres { get; set; } = new List<MovieGenre>();
    }
}